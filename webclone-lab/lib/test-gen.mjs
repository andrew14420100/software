// Generates a Playwright Test suite that checks the clone against facts
// recorded from the original (navigation, structure, controls, forms, layout, API).
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

export function writeTests({ dir, cfg, base, apiBase, lab, chromium, devices }) {
  const tdir = path.join(dir, "tests");
  fs.mkdirSync(tdir, { recursive: true });
  const pwt = pathToFileURL(path.join(lab, "node_modules/@playwright/test/index.mjs")).href;
  const projects = Object.entries(devices).filter(([n]) => cfg.devices.includes(n))
    .map(([name, use]) => ({ name, use: { ...use, launchOptions: { executablePath: chromium } } }));
  const config = {
    testDir: ".", testMatch: "wcl.spec.mjs", timeout: 60000, workers: 2, retries: 0,
    reporter: [["list"], ["json", { outputFile: "../research/test-results/results.json" }]],
    outputDir: "../research/test-results/artifacts",
    use: { baseURL: base, trace: "off", screenshot: "only-on-failure" },
    projects,
  };
  fs.writeFileSync(path.join(tdir, "playwright.config.mjs"), `export default ${JSON.stringify(config, null, 2)};\n`);
  const spec = `// GENERATED by wcl test — expectations come from research/facts/original
import { test, expect } from ${JSON.stringify(pwt)};
import fs from "node:fs";
import path from "node:path";

const ROOT = ${JSON.stringify(dir)};
const ORIGIN = ${JSON.stringify(cfg.origin)};
const ROUTES = ${JSON.stringify(cfg.routes)};
const API = ${JSON.stringify(apiBase)};
const slug = (p) => p.replace(/^\\/+|\\/+$/g, "").replace(/[^a-zA-Z0-9._-]+/g, "_") || "index";
const facts = (dev, route) => { const f = path.join(ROOT, "research/facts/original", dev, slug(route) + ".json"); return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, "utf8")).facts : null; };
const local = (href) => { try { const u = new URL(href); return u.origin === ORIGIN ? u.pathname + u.search : null; } catch { return null; } };
const norm = (s) => (s || "").replace(/\\s+/g, " ").trim();

for (const route of ROUTES) {
  test.describe(route, () => {
    test("loads without runtime errors", async ({ page }) => {
      const errors = []; page.on("pageerror", (e) => errors.push(e.message));
      const resp = await page.goto(route, { waitUntil: "load" });
      expect(resp.status(), "HTTP status").toBeLessThan(400);
      await page.waitForLoadState("networkidle").catch(() => {});
      expect(errors, "uncaught exceptions").toEqual([]);
    });

    test("structure matches original", async ({ page }, info) => {
      const o = facts(info.project.name, route); test.skip(!o, "no original facts");
      await page.goto(route, { waitUntil: "load" }); await page.waitForLoadState("networkidle").catch(() => {});
      expect.soft(await page.title(), "title").toBe(o.title);
      const vis = (sel) => page.locator(sel).filter({ visible: true });
      const heads = await vis("h1,h2,h3").evaluateAll((els) => els.map((e) => e.tagName + ":" + (e.innerText || "").replace(/\\s+/g, " ").trim()));
      expect.soft(heads.slice(0, 60), "headings").toEqual(o.headings);
      const btns = await vis("button,[role=button],input[type=submit]").evaluateAll((els) => els.map((b) => ((b.innerText || b.textContent || "").replace(/\\s+/g, " ").trim().slice(0, 80) || b.getAttribute("aria-label") || "")));
      expect.soft(btns.slice(0, 100), "buttons").toEqual(o.buttons);
      const links = await vis("a[href]").evaluateAll((as) => as.map((a) => (a.innerText || a.textContent || "").replace(/\\s+/g, " ").trim().slice(0, 80)));
      expect.soft(links.slice(0, 200), "link texts").toEqual(o.links.map((l) => l.text));
      const forms = await page.locator("form").evaluateAll((fs) => fs.map((f) => [...f.elements].map((e) => e.name).filter(Boolean)));
      expect.soft(forms, "form fields").toEqual(o.forms.map((f) => f.fields));
    });

    test("internal navigation resolves", async ({ page, request }, info) => {
      const o = facts(info.project.name, route); test.skip(!o, "no original facts");
      const targets = [...new Set(o.links.map((l) => local(l.href)).filter(Boolean))];
      for (const t of targets) { const r = await request.get(t); expect.soft(r.status(), "link " + t).toBeLessThan(400); }
      // click-through: each internal link must land on the same path as the original
      await page.goto(route);
      for (const l of o.links.filter((l) => local(l.href)).slice(0, 15)) {
        await page.goto(route); await page.waitForLoadState("networkidle").catch(() => {});
        const a = page.locator("a[href]").filter({ visible: true, hasText: l.text || undefined }).first();
        if (!(await a.count())) { expect.soft(false, "missing link " + l.text).toBe(true); continue; }
        const want = new URL(l.href).pathname;
        await a.click();
        // works for full page loads and client-side (SPA) navigation alike
        await page.waitForURL((u) => u.pathname === want, { timeout: 8000 }).catch(() => {});
        expect.soft(new URL(page.url()).pathname, "navigates like original: " + l.text).toBe(want);
      }
    });

    test("controls are interactive", async ({ page }, info) => {
      const o = facts(info.project.name, route); test.skip(!o || !o.buttons.length, "no controls");
      const errors = []; page.on("pageerror", (e) => errors.push(e.message));
      await page.goto(route); await page.waitForLoadState("networkidle").catch(() => {});
      const btns = page.locator("button,[role=button]").filter({ visible: true });
      const n = Math.min(await btns.count(), 15);
      for (let i = 0; i < n; i++) {
        const b = btns.nth(i); if (!(await b.isVisible())) continue;
        const before = await page.evaluate(() => document.body.innerHTML.length + location.href);
        await b.click({ timeout: 5000 }).catch((e) => errors.push("click: " + e.message.split("\\n")[0]));
        await page.waitForTimeout(250);
        const after = await page.evaluate(() => document.body.innerHTML.length + location.href);
        info.annotations.push({ type: "control", description: (await b.textContent().catch(() => "?")) + (before === after ? " (no DOM change)" : " (changes UI)") });
        if (page.url().replace(/#.*/, "") !== new URL(route, page.url()).href.replace(/#.*/, "")) await page.goto(route);
      }
      expect(errors, "errors while interacting").toEqual([]);
    });

    test("controls behave like original", async ({ page }, info) => {
      const o = facts(info.project.name, route); test.skip(!o || !(o.controls || []).length, "no probed controls");
      const sig = () => page.evaluate(() => location.pathname + "|" + document.body.innerHTML);
      for (const c of o.controls) {
        await page.goto(route); await page.waitForLoadState("networkidle").catch(() => {});
        const b = page.locator("button:not([type=submit]),[role=button]").filter({ visible: true, hasText: c.label || undefined }).first();
        if (!(await b.count())) { expect.soft(false, "missing control " + c.label).toBe(true); continue; }
        const before = await sig(); await b.click({ timeout: 5000 }).catch(() => {}); await page.waitForTimeout(300);
        expect.soft(before !== (await sig()), "control '" + c.label + "' changes UI like original").toBe(c.changes);
      }
    });

    test("responsive: no horizontal overflow", async ({ page }) => {
      await page.goto(route); await page.waitForLoadState("networkidle").catch(() => {});
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
      expect(overflow).toBeLessThanOrEqual(1);
    });
  });
}

const routesFile = path.join(ROOT, "backend/routes.json");
if (API && fs.existsSync(routesFile)) {
  test.describe("reconstructed API", () => {
    for (const r of JSON.parse(fs.readFileSync(routesFile, "utf8")).filter((r) => r.method === "GET" && !r.path.includes(":id"))) {
      test("GET " + r.path, async ({ request }, info) => {
        test.skip(info.project.name !== "desktop", "API checked once");
        const res = await request.get(API + r.path); expect(res.status()).toBeLessThan(400);
      });
    }
    test("CRUD round-trip", async ({ request }, info) => {
      test.skip(info.project.name !== "desktop", "API checked once");
      const list = JSON.parse(fs.readFileSync(routesFile, "utf8")).find((r) => r.op === "create"); test.skip(!list, "no collection");
      const sample = (await (await request.get(API + list.path)).json()); const rows = Array.isArray(sample) ? sample : Object.values(sample).find(Array.isArray) || [];
      const { id: _drop, ...record } = rows[0] || { name: "wcl-test" };
      const c = await request.post(API + list.path, { data: record }); expect(c.status()).toBe(201);
      const row = await c.json();
      expect((await request.get(API + list.path + "/" + row.id)).status()).toBe(200);
      expect((await request.patch(API + list.path + "/" + row.id, { data: { name: "wcl-test-2" } })).status()).toBe(200);
      expect((await request.delete(API + list.path + "/" + row.id)).status()).toBe(204);
    });
  });
}
`;
  fs.writeFileSync(path.join(tdir, "wcl.spec.mjs"), spec);
  return path.join(tdir, "playwright.config.mjs");
}
